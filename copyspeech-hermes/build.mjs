// Bundles the plugin sources in src/ into the two files the repo ships:
// - plugin.js: the file the Hermes loader reads. Its only export is the default plugin.
// - test/under-test.mjs: the same modules plus the internals that plugin.test.mjs checks.
//
// Run from the repo root: bun copyspeech-hermes/build.mjs
// Check without writing:  bun copyspeech-hermes/build.mjs --check
// The Hermes loader rejects relative imports, so the bundle is the one file it can load.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SDK_EXTERNALS = ["@hermes/plugin-sdk", "react", "react/jsx-runtime"];
const BANNER = "// GENERATED by copyspeech-hermes/build.mjs from src/. Edit src/, then rebuild.\n";
const OUTPUTS = [
  { entry: "src/index.js", file: "plugin.js" },
  { entry: "src/testing.js", file: "test/under-test.mjs" }
];
const checkOnly = process.argv.includes("--check");

async function bundle(entry) {
  const result = await Bun.build({
    entrypoints: [join(here, entry)],
    format: "esm",
    target: "browser",
    external: SDK_EXTERNALS,
    minify: false
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    process.exit(1);
  }
  return BANNER + hoistImports(await result.outputs[0].text());
}

// Bun keeps each module's imports where that module sat. Move them to the top, one
// per line, so the loader and the test harness see one import block.
function hoistImports(code) {
  const imports = new Set();
  const body = code.replace(/^import [^\n]*;\n/gm, (line) => {
    imports.add(line);
    return "";
  });
  if (/^import /m.test(body)) throw new Error("bundle has an import Bun did not hoist");
  return [...imports].join("") + body;
}

let stale = [];
for (const output of OUTPUTS) {
  const built = await bundle(output.entry);
  const target = join(here, output.file);
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (checkOnly) {
    if (current !== built) stale.push(output.file);
  } else {
    writeFileSync(target, built);
    console.log("wrote " + output.file + " (" + built.split("\n").length + " lines)");
  }
}

if (checkOnly && stale.length > 0) {
  console.error(
    "stale build output: " + stale.join(", ") + ". Run: bun copyspeech-hermes/build.mjs"
  );
  process.exit(1);
}
if (checkOnly) console.log("build output is current");
